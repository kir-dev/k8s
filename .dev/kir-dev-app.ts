/** A container workload being built; returned by `addDocker`. */
export class DockerBuilder {
    /** @internal */ readonly ports: Port[] = [];

    constructor(readonly options: DockerOptions) {}

    /** Declare a container port; the workload's Service exposes it. */
    port(port: number, name?: string): Port {
        const portName = name ?? (this.ports.length === 0 ? "http" : `port-${port}`);
        const endpoint = new Port(this, portName, port);
        this.ports.push(endpoint);
        return endpoint;
    }
}

/** A workload port; its Service is published via `.publish()`. */
export class Port {
    /** @internal */ readonly ingresses: { host: string; options: ExposeOptions }[] = [];

    constructor(
        /** @internal */ readonly workload: DockerBuilder,
        readonly name: string,
        readonly number: number,
    ) {}

    /** Publish this port at `host` through Traefik, with a cert-manager certificate. */
    publish(host: string, options: ExposeOptions = {}): this {
        this.ingresses.push({ host, options });
        return this;
    }
}

export interface ExposeOptions {
    name?: string;
    paths?: { path?: string; pathType?: string; service?: string; port?: string }[];
    middlewares?: string[];
    ingressClassName?: string;
    tlsSecretName?: string;
    annotations?: Record<string, string>;
    /** Ingress labels. Default the app's labels; pass `{}` to omit them. */
    labels?: Record<string, string>;
}

// --- builder --------------------------------------------------------------

export class KirDevApp {
    readonly app: App;
    readonly name: string;
    readonly namespace: string;
    /** The Chart resources are added to; also the `.configure()` scope. */
    readonly chart: Construct;

    private readonly backups?: BackupsOptions & { credentialsSecret: string; postgresPrefix: string };
    private readonly syncWaves: boolean;
    private readonly devSecrets?: Record<string, string>;
    private readonly declaredSecrets = new Set<string>();
    private readonly dockerBuilders: DockerBuilder[] = [];
    private postgresAdded = false;
    /** The standard `app.kubernetes.io/*` labels, merged with `options.labels`. */
    readonly labels: Record<string, string>;

    constructor(name: string, options: KirDevAppOptions = {}) {
        this.name = name;
        this.namespace = options.namespace ?? name;
        this.syncWaves = options.syncWaves ?? true;
        this.devSecrets = options.devSecrets;

        this.app = new App();
        this.chart = new Chart(this.app, "chart", { namespace: this.namespace });
        if (options.createNamespace ?? true) {
            const namespaceChart = new Chart(this.app, "namespace");
            new kube.KubeNamespace(namespaceChart, "namespace", { metadata: { name: this.namespace } });
        }

        this.labels = {
            "app.kubernetes.io/name": name,
            "app.kubernetes.io/instance": name,
            "app.kubernetes.io/component": "server",
            "app.kubernetes.io/part-of": name,
            ...options.labels,
        };

        if (options.backups) {
            this.backups = {
                credentialsSecret: `${name}-backups-secrets`,
                postgresPrefix: "postgres/",
                ...options.backups,
            };
        }
    }

    /** Sync-wave annotation, or nothing when `syncWaves` is disabled. */
    private wave(step: number): Record<string, string> {
        return this.syncWaves ? { "argocd.argoproj.io/sync-wave": String(step) } : {};
    }

    /** `{ annotations }` metadata fragment for a sync wave, omitted when disabled. */
    private waveAnnotation(step: number): { annotations?: Record<string, string> } {
        const wave = this.wave(step);
        return Object.keys(wave).length > 0 ? { annotations: wave } : {};
    }

    /**
     * Declare a Secret whose values are filled in by hand. Idempotent: repeated
     * calls with the same name are no-ops, so `manualSecret()` and the
     * `secrets` option can both target it.
     */
    declareSecret(name: string, stringData?: Record<string, string>): void {
        if (this.declaredSecrets.has(name)) return;
        this.declaredSecrets.add(name);
        new kube.KubeSecret(this.chart, name, {
            metadata: { name, ...this.waveAnnotation(-25) },
            stringData,
        });
    }

    /** Register a key of a manual secret; creates `${name}-secrets` on first use. */
    appSecrets(): string {
        const name = `${this.name}-secrets`;
        this.declareSecret(name, environment.environment == "Development" ? this.devSecrets : undefined);
        return name;
    }

    // --- postgres ---------------------------------------------------------

    addPostgres(options: PostgresOptions): PostgresHandle {
        if (this.postgresAdded) throw new Error(`${this.name}: addPostgres can only be called once`);
        this.postgresAdded = true;

        const name = this.name;
        // The database and owner are the app name.
        const database = name;
        const owner = name;
        const clusterName = `${name}-db`;
        const secretName = `${clusterName}-app`;

        const backupEnabled = this.resolveBackup(options.backup);
        const restore = options.restore === "latest";
        const externalClusterName = options.externalClusterName ?? "barman-backup";
        const image = options.image;

        const resources = options.resources ?? POSTGRES_RESOURCES;
        const baseSpec: cnpg.ClusterSpec = {
            primaryUpdateStrategy: cnpg.ClusterSpecPrimaryUpdateStrategy.UNSUPERVISED,
            primaryUpdateMethod: cnpg.ClusterSpecPrimaryUpdateMethod.SWITCHOVER,
            instances: options.instances ?? 2,
            imageName: image,
            imagePullPolicy: options.imagePullPolicy ?? "IfNotPresent",
            monitoring: { enablePodMonitor: options.monitoring ?? true },
            postgresql: {
                parameters: { wal_level: "replica", shared_buffers: "128MB", ...options.parameters },
            },
            resources: cnpgResources(resources),
            storage: {
                size: options.size ?? "1.5Gi",
                storageClass: options.storageClass ?? "node-local-zfs",
            },
        };

        const clusterSpec: cnpg.ClusterSpec = {
            ...baseSpec,
            ...(restore
                ? {
                      externalClusters: [
                          {
                              name: externalClusterName,
                              plugin: {
                                  name: "barman-cloud.cloudnative-pg.io",
                                  enabled: true,
                                  isWalArchiver: false,
                                  parameters: { barmanObjectName: `${name}-backups`, serverName: clusterName },
                              },
                          },
                      ],
                  }
                : {}),
            bootstrap: restore
                ? { recovery: { source: externalClusterName, database, owner } }
                : { initdb: { database, owner } },
            ...(restore || backupEnabled
                ? {
                      plugins: [
                          {
                              name: "barman-cloud.cloudnative-pg.io",
                              enabled: true, // needed otherwise ArgoCD complains about being OutOfSync
                              isWalArchiver: backupEnabled,
                              parameters: { barmanObjectName: `${name}-backups` },
                          },
                      ],
                  }
                : {}),
        };

        if (this.backups) this.emitBackupSecret();

        if (backupEnabled) {
            new barman.ObjectStore(this.chart, `${name}-backups`, {
                metadata: {
                    name: `${name}-backups`,
                    ...this.waveAnnotation(-21),
                },
                spec: {
                    instanceSidecarConfiguration: {
                        resources: barmanResources(BARMAN_RESOURCES),
                    },
                    configuration: {
                        destinationPath: `s3://${this.backups!.bucket}/${this.backups!.postgresPrefix}`,
                        endpointUrl: this.backups!.endpoint,
                        s3Credentials: {
                            accessKeyId: { name: this.backups!.credentialsSecret, key: "ACCESS_KEY_ID" },
                            secretAccessKey: { name: this.backups!.credentialsSecret, key: "ACCESS_SECRET_KEY" },
                        },
                        wal: {
                            compression: barman.ObjectStoreSpecConfigurationWalCompression.GZIP,
                            maxParallel: 8,
                        },
                    },
                },
            });
        }

        new cnpg.Cluster(this.chart, clusterName, {
            metadata: {
                name: clusterName,
                labels: {
                    "app.kubernetes.io/name": "postgres",
                    "app.kubernetes.io/instance": `postgres-${name}`,
                    "app.kubernetes.io/component": "database",
                    "app.kubernetes.io/part-of": name,
                },
                ...this.waveAnnotation(-20),
            },
            spec: clusterSpec,
        });

        if (backupEnabled) {
            const backup = typeof options.backup === "object" ? options.backup : {};
            const scheduledBackupName = backup.name ?? `${name}-db-backup`;
            new cnpg.ScheduledBackup(this.chart, scheduledBackupName, {
                metadata: { name: scheduledBackupName },
                spec: {
                    cluster: { name: clusterName },
                    schedule: backup.schedule ?? "0 24 3 * * *",
                    backupOwnerReference: cnpg.ScheduledBackupSpecBackupOwnerReference.SELF,
                    method: cnpg.ScheduledBackupSpecMethod.PLUGIN,
                    pluginConfiguration: { name: "barman-cloud.cloudnative-pg.io" },
                },
            });
        }

        const pgRef = (key: string, envName: string) => new SecretKeyRef(secretName, key, envName);
        const handle: PostgresHandle = {
            clusterName,
            secretName,
            host: pgRef("host", "DBHOST"),
            port: pgRef("port", "DBPORT"),
            database: pgRef("dbname", "DBNAME"),
            user: pgRef("user", "DBUSER"),
            password: pgRef("password", "DBPASSWORD"),
            uri: pgRef("uri", "DATABASE_URI"),
            jdbcUri: pgRef("jdbc-uri", "JDBC_DATABASE_URL"),
            dotnetConnectionString() {
                return interpolate`Host=${this.host}; Database=${this.database}; Username=${this.user}; Password=${this.password};`;
            },
        };
        return handle;
    }

    // --- s3 (garage) ------------------------------------------------------

    addGarage(options: S3Options): S3Handle {
        const name = this.name;
        const clusterName = options.clusterName ?? `${name}-garage`;
        const credentialsSecret = options.credentialsSecret ?? `${name}-garage-s3`;
        const buckets = options.buckets;
        if (buckets.length === 0) throw new Error(`s3() for ${name}: at least one bucket is required`);

        const backupEnabled = this.resolveBackup(options.backup);
        const backup = typeof options.backup === "object" ? options.backup : {};
        const lifecycle = backup.lifecycle ?? "fresh";
        const restoring = lifecycle === "restore" || lifecycle === "restored";

        const garageLabels = {
            "app.kubernetes.io/name": clusterName,
            "app.kubernetes.io/part-of": name,
        };
        const garageBackupLabels = { [`backup.kir-dev.hu/${clusterName}`]: "true" };
        const storageClassName = storageClass(ProdStorageClass.memorySsd, DevStorageClass.snapshottableHostPath);
        const volumeSnapshotClassName = environment.environment == "Production" ? "memory" : "csi-hostpath-snapclass";

        new garage.GarageAdminTokenV1Beta1(this.chart, `${clusterName}-admin`, {
            metadata: {
                name: `${clusterName}-admin`,
                labels: garageLabels,
                ...this.waveAnnotation(-30),
            },
            spec: {
                clusterRef: { name: clusterName },
                secretTemplate: { name: `${clusterName}-admin`, tokenKey: "admin-token" },
            },
        });

        const volumes = [
            { name: "data", size: backup.dataSize ?? "5Gi" },
            { name: "metadata", size: backup.metadataSize ?? "1Gi" },
        ] as const;

        const volumeStorage = (volume: (typeof volumes)[number]) => ({
            type: garage.GarageClusterV1Beta2SpecStorageDataType.PERSISTENT_VOLUME_CLAIM,
            size: garage.GarageClusterV1Beta2SpecStorageDataSize.fromString(volume.size),
            storageClassName,
            labels: garageBackupLabels,
            dataSourceRef: restoring
                ? {
                      apiGroup: "snapshot.storage.k8s.io",
                      kind: "VolumeSnapshot",
                      name: garageBackupName(volume.name, "restore-snap"),
                  }
                : undefined,
        });

        new garage.GarageClusterV1Beta2(this.chart, clusterName, {
            metadata: {
                name: clusterName,
                labels: garageLabels,
                ...this.waveAnnotation(-20),
            },
            spec: {
                zone: "default",
                replication: { factor: 1 },
                storage: {
                    replicas: 1,
                    // Declared explicitly (like the GarageKey defaults below):
                    // the operator only defaults these, and ArgoCD would
                    // otherwise see the GarageCluster as OutOfSync and trip the
                    // operator's immutable-storage admission webhook.
                    dataFsync: false,
                    metadataFsync: false,
                    metadata: {
                        ...volumeStorage(volumes[1]),
                        type: garage.GarageClusterV1Beta2SpecStorageMetadataType.PERSISTENT_VOLUME_CLAIM,
                        size: garage.GarageClusterV1Beta2SpecStorageMetadataSize.fromString(volumes[1].size),
                    },
                    data: {
                        ...volumeStorage(volumes[0]),
                        type: garage.GarageClusterV1Beta2SpecStorageDataType.PERSISTENT_VOLUME_CLAIM,
                        size: garage.GarageClusterV1Beta2SpecStorageDataSize.fromString(volumes[0].size),
                    },
                    podDisruptionBudget: { enabled: false },
                    resources: garageResources(GARAGE_RESOURCES),
                },
                network: {
                    rpcBindPort: 3901,
                    service: { type: garage.GarageClusterV1Beta2SpecNetworkServiceType.CLUSTER_IP },
                },
                s3Api: { bindPort: 3900, region: "us-east-1" },
                admin: {
                    bindPort: 3903,
                    adminTokenSecretRef: { name: `${clusterName}-admin`, key: "admin-token" },
                },
            },
        });

        for (const bucket of buckets) {
            new garage.GarageBucketV1Beta1(this.chart, bucket, {
                metadata: {
                    name: bucket,
                    labels: garageLabels,
                    ...this.waveAnnotation(-15),
                },
                spec: { clusterRef: { name: clusterName }, globalAlias: bucket },
            });
        }

        const keyName = buckets[0];
        new garage.GarageKeyV1Beta1(this.chart, `${keyName}-key`, {
            metadata: {
                name: keyName,
                labels: garageLabels,
                ...this.waveAnnotation(-10),
            },
            spec: {
                clusterRef: { name: clusterName },
                name: keyName,
                // The operator's defaults; declaring them keeps ArgoCD from
                // reporting OutOfSync forever (the webhook writes them back).
                neverExpires: false,
                secretTemplate: {
                    name: credentialsSecret,
                    type: "Opaque",
                    accessKeyIdKey: "access-key-id",
                    secretAccessKeyKey: "secret-access-key",
                    endpointKey: "endpoint",
                    hostKey: "host",
                    schemeKey: "scheme",
                    regionKey: "region",
                    bucketNameKey: "bucket",
                    websiteUrlKey: "website-url",
                    credentialsFileKey: "credentials",
                    credentialsFileProfile: "default",
                },
                bucketPermissions: buckets.map((bucket) => ({
                    bucketRef: { name: bucket },
                    read: true,
                    write: true,
                    owner: false,
                })),
            },
        });

        if (backupEnabled) {
            this.emitGarageBackups({
                clusterName,
                volumes,
                storageClassName,
                volumeSnapshotClassName,
                lifecycle,
                schedule: backup.schedule,
                retain: backup.retain,
                pruneIntervalDays: backup.pruneIntervalDays,
            });
        }

        const handle: S3Handle = {
            clusterName,
            endpoint: `http://${clusterName}:3900`,
            bucket: buckets[0],
            bucketNames: buckets,
            region: "us-east-1",
            credentialsSecret,
            accessKeyId: new SecretKeyRef(credentialsSecret, "access-key-id", "S3_ACCESS_KEY_ID"),
            secretAccessKey: new SecretKeyRef(credentialsSecret, "secret-access-key", "S3_SECRET_ACCESS_KEY"),
        };
        return handle;
    }

    // --- workload ---------------------------------------------------------

    addDocker(options: DockerOptions): DockerBuilder {
        const workload = new DockerBuilder(options);
        this.dockerBuilders.push(workload);
        return workload;
    }

    private materializeDocker(workload: DockerBuilder): void {
        const options = workload.options;
        const base = options.name ?? this.name;
        const containerName = options.containerName ?? base;
        const ports = workload.ports;
        const defaultPortName = ports[0]?.name ?? "http";
        const labels = { ...(options.labels ?? this.labels) };

        // String env values go into the ConfigMap; refs become per-key env vars.
        const configData: Record<string, string> = {};
        const envVars: kube.EnvVar[] = [];
        for (const [name, value] of Object.entries(options.env ?? {})) {
            if (typeof value === "string") configData[name] = value;
            else envVars.push(...value.apply(name, this));
        }

        const envFrom: kube.EnvFromSource[] = [];
        if (Object.keys(configData).length > 0) {
            new kube.KubeConfigMap(this.chart, `${base}-config`, {
                metadata: { name: `${base}-config`, ...this.waveAnnotation(-25) },
                data: configData,
            });
            envFrom.push({ configMapRef: { name: `${base}-config` } });
        }

        // `.port()` declares the Service; each port is published via `.publish()`.
        if (ports.length > 0) {
            new kube.KubeService(this.chart, `${base}-service`, {
                metadata: { name: base, labels },
                spec: {
                    selector: labels,
                    ports: ports.map((port) => ({
                        name: port.name,
                        port: port.number,
                        targetPort: kube.IntOrString.fromString(port.name),
                    })),
                },
            });
        }

        new kube.KubeDeployment(this.chart, `${base}-deployment`, {
            metadata: { name: base, labels },
            spec: {
                replicas: options.replicas ?? 1,
                selector: { matchLabels: labels },
                template: {
                    metadata: { labels },
                    spec: {
                        automountServiceAccountToken: options.automountServiceAccountToken ?? false,
                        containers: [
                            {
                                name: containerName,
                                image: options.image,
                                imagePullPolicy: options.imagePullPolicy ?? "IfNotPresent",
                                ports:
                                    ports.length > 0
                                        ? ports.map((port) => ({
                                              containerPort: port.number,
                                              protocol: "TCP",
                                              name: port.name,
                                          }))
                                        : undefined,
                                env: envVars.length > 0 ? envVars : undefined,
                                envFrom: envFrom.length > 0 ? envFrom : undefined,
                                startupProbe: options.startupProbe
                                    ? httpProbe(options.startupProbe, defaultPortName)
                                    : undefined,
                                readinessProbe: options.readinessProbe
                                    ? httpProbe(options.readinessProbe, defaultPortName)
                                    : undefined,
                                livenessProbe: options.livenessProbe
                                    ? tcpProbe(options.livenessProbe, defaultPortName)
                                    : undefined,
                                resources: kubeResources(options.resources ?? WORKLOAD_RESOURCES),
                            },
                        ],
                        restartPolicy: "Always",
                    },
                },
            },
        });

        for (const port of ports) {
            for (const ingress of port.ingresses) {
                this.addIngress(base, port.name, ingress.host, ingress.options);
            }
        }
    }

    private addIngress(service: string, portName: string, host: string, options: ExposeOptions = {}): void {
        const ingressName = options.name ?? this.name;
        const middlewares = options.middlewares ?? [];

        const annotations: Record<string, string> = {
            "cert-manager.io/cluster-issuer": "letsencrypt",
            "acme.cert-manager.io/http01-ingress-class": "traefik",
            ...options.annotations,
        };
        if (middlewares.length > 0) {
            annotations["traefik.ingress.kubernetes.io/router.middlewares"] = middlewares.join(",");
        }

        const paths = options.paths ?? [{ path: "/", pathType: "Prefix", service, port: portName }];
        const labels = options.labels ?? this.labels;

        new kube.KubeIngress(this.chart, ingressName, {
            metadata: {
                name: ingressName,
                ...(Object.keys(labels).length > 0 ? { labels } : {}),
                annotations,
            },
            spec: {
                ingressClassName: options.ingressClassName ?? "traefik",
                tls: [{ hosts: [host], secretName: options.tlsSecretName ?? `${ingressName}-tls-cert` }],
                rules: [
                    {
                        host,
                        http: {
                            paths: paths.map((path) => ({
                                path: path.path ?? "/",
                                pathType: path.pathType ?? "Prefix",
                                backend: {
                                    service: { name: path.service ?? service, port: { name: path.port ?? "http" } },
                                },
                            })),
                        },
                    },
                ],
            },
        });
    }

    /** Escape hatch: the raw cdk8s scope and the app. */
    configure(fn: (context: { scope: Construct; app: KirDevApp }) => void): this {
        fn({ scope: this.chart, app: this });
        return this;
    }

    synth(): void {
        for (const workload of this.dockerBuilders) this.materializeDocker(workload);
        this.app.synth();
    }

    // --- internals --------------------------------------------------------

    private resolveBackup(backup: unknown): boolean {
        if (backup === false) return false;
        if (this.backups == null) {
            if (backup != null)
                throw new Error(`${this.name}: backups requested but no app-level \`backups\` configured`);
            return false;
        }
        return true;
    }

    private emitBackupSecret(): void {
        const credentialsSecret = this.backups!.credentialsSecret;
        new kube.KubeSecret(this.chart, credentialsSecret, {
            metadata: {
                name: credentialsSecret,
                annotations: {
                    ...this.wave(-22),
                    // The credentials are filled in manually; keep ArgoCD from
                    // pruning the extra `data` keys it doesn't declare.
                    "argocd.argoproj.io/compare-options": "IgnoreExtraneous",
                },
            },
            // Set manually:
            // stringData:
            //   ACCESS_KEY_ID:
            //   ACCESS_SECRET_KEY:
        });
    }

    private emitGarageBackups(options: {
        clusterName: string;
        volumes: readonly { name: string; size: string }[];
        storageClassName: string;
        volumeSnapshotClassName: string;
        lifecycle: "fresh" | "restore" | "restored";
        schedule?: string;
        retain?: { daily?: number; weekly?: number; monthly?: number };
        pruneIntervalDays?: number;
    }): void {
        const name = this.name;
        const backups = this.backups!;

        for (const volume of options.volumes) {
            const repository = garageBackupName(volume.name, "backup");
            // The PVC names the garage-operator's StatefulSet creates:
            // `<volumeClaimTemplate>-<statefulset>-<ordinal>`.
            const pvc = `${volume.name}-${options.clusterName}-storage-0-0`;
            const restorePvc = garageBackupName(volume.name, "restore");
            const restoreSnapshot = garageBackupName(volume.name, "restore-snap");

            new kube.KubeSecret(this.chart, repository, {
                metadata: {
                    name: repository,
                    annotations: {
                        ...this.wave(-26),
                        "argocd.argoproj.io/compare-options": "IgnoreExtraneous",
                    },
                },
                stringData: {
                    RESTIC_REPOSITORY: `s3:${backups.endpoint}/${backups.bucket}/restic/${pvc}`,
                    AWS_DEFAULT_REGION: backups.region,
                },
                // Set manually:
                // stringData:
                //   RESTIC_PASSWORD:
                //   AWS_ACCESS_KEY_ID:
                //   AWS_SECRET_ACCESS_KEY:
            });

            if (options.lifecycle === "restore") {
                new kube.KubePersistentVolumeClaim(this.chart, `${repository}-restore-pvc`, {
                    metadata: {
                        name: restorePvc,
                        annotations: {
                            ...this.wave(-25),
                            "volsync.backube/snapname": restoreSnapshot,
                        },
                    },
                    spec: {
                        accessModes: ["ReadWriteOnce"],
                        storageClassName: options.storageClassName,
                        resources: { requests: { storage: kube.Quantity.fromString(volume.size) } },
                    },
                });

                new ApiObject(this.chart, `${repository}-destination`, {
                    apiVersion: "volsync.backube/v1alpha1",
                    kind: "ReplicationDestination",
                    metadata: {
                        name: repository,
                        ...this.waveAnnotation(-24),
                    },
                    spec: {
                        trigger: { manual: "restore-once" },
                        restic: {
                            repository,
                            destinationPVC: restorePvc,
                            copyMethod: "Snapshot",
                            volumeSnapshotClassName: options.volumeSnapshotClassName,
                            cacheStorageClassName: options.storageClassName,
                        },
                    },
                });
            } else {
                new ApiObject(this.chart, `${repository}-source`, {
                    apiVersion: "volsync.backube/v1alpha1",
                    kind: "ReplicationSource",
                    metadata: {
                        name: repository,
                        ...this.waveAnnotation(-25),
                    },
                    spec: {
                        sourcePVC: pvc,
                        trigger: { schedule: options.schedule ?? "45 3 * * *" },
                        restic: {
                            repository,
                            copyMethod: "Snapshot",
                            volumeSnapshotClassName: options.volumeSnapshotClassName,
                            // Pin the restic cache PVC's class: otherwise it
                            // falls back to the cluster default.
                            cacheStorageClassName: options.storageClassName,
                            retain: {
                                daily: options.retain?.daily ?? 7,
                                weekly: options.retain?.weekly ?? 4,
                                monthly: options.retain?.monthly ?? 6,
                            },
                            pruneIntervalDays: options.pruneIntervalDays ?? 7,
                        },
                    },
                });
            }
        }
    }
}

export function createKirDevApp(name: string, options: KirDevAppOptions = {}): KirDevApp {
    return new KirDevApp(name, options);
}

// --- helpers --------------------------------------------------------------

// The restic repository / restore resource names for a Garage volume. Kept
// independent of the cluster name for compatibility with existing apps.
function garageBackupName(volume: string, suffix: string): string {
    return `garage-${volume}-${suffix}`;
}

function httpProbe(options: ProbeOptions, defaultPort: string): kube.Probe {
    return {
        httpGet: {
            path: options.path ?? "/",
            port: kube.IntOrString.fromString(options.port ?? defaultPort),
        },
        periodSeconds: options.periodSeconds ?? 10,
        timeoutSeconds: options.timeoutSeconds ?? 3,
        failureThreshold: options.failureThreshold ?? 3,
        initialDelaySeconds: options.initialDelaySeconds,
    };
}

function tcpProbe(options: ProbeOptions, defaultPort: string): kube.Probe {
    return {
        tcpSocket: { port: kube.IntOrString.fromString(options.port ?? defaultPort) },
        periodSeconds: options.periodSeconds ?? 20,
        timeoutSeconds: options.timeoutSeconds ?? 3,
        failureThreshold: options.failureThreshold ?? 6,
        initialDelaySeconds: options.initialDelaySeconds,
    };
}

function kubeResources(spec: ResourceSpec): kube.ResourceRequirements {
    const quantities = (set?: Record<string, string>) =>
        set && Object.fromEntries(Object.entries(set).map(([key, value]) => [key, kube.Quantity.fromString(value)]));
    return { limits: quantities(spec.limits), requests: quantities(spec.requests) };
}

function cnpgResources(spec: ResourceSpec): cnpg.ClusterSpecResources {
    return {
        limits:
            spec.limits &&
            Object.fromEntries(
                Object.entries(spec.limits).map(([key, value]) => [
                    key,
                    cnpg.ClusterSpecResourcesLimits.fromString(value),
                ]),
            ),
        requests:
            spec.requests &&
            Object.fromEntries(
                Object.entries(spec.requests).map(([key, value]) => [
                    key,
                    cnpg.ClusterSpecResourcesRequests.fromString(value),
                ]),
            ),
    };
}

