// --- handles --------------------------------------------------------------

export interface PostgresHandle {
    readonly clusterName: string;
    /** The `<cluster>-app` Secret CNPG generates. */
    readonly secretName: string;
    readonly host: SecretKeyRef;
    readonly port: SecretKeyRef;
    readonly database: SecretKeyRef;
    readonly user: SecretKeyRef;
    readonly password: SecretKeyRef;
    /** A ready-to-use `postgresql://...` URI. */
    readonly uri: SecretKeyRef;
    readonly jdbcUri: SecretKeyRef;
    /**
     * A .NET-style connection string built from the parts, e.g.
     * `Host=$(DBHOST); Database=$(DBNAME); Username=$(DBUSER); Password=$(DBPASSWORD);`.
     */
    dotnetConnectionString(): Interpolated;
}

export interface S3Handle {
    readonly clusterName: string;
    /** In-cluster endpoint, e.g. `http://ehk-garage:3900`. */
    readonly endpoint: string;
    /** The first (usually only) bucket name. */
    readonly bucket: string;
    readonly bucketNames: string[];
    readonly region: string;
    /** The Secret the garage-operator writes the app's key pair into. */
    readonly credentialsSecret: string;
    readonly accessKeyId: SecretKeyRef;
    readonly secretAccessKey: SecretKeyRef;
}

