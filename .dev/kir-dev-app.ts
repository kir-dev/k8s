// Builder for the standard Kir-Dev app shape.
//
// An app is a container workload exposed through Traefik, optionally backed by
// a CNPG Postgres cluster and/or a Garage S3 cluster. Postgres is backed up
// off-site with the Barman Cloud plugin (CNPG's `ObjectStore` +
// `ScheduledBackup`); Garage's volumes are backed up off-site with
// VolSync/restic. Both share one Backblaze B2 bucket, split by prefix.
//
// Infra resources (`.postgres()`, `.s3()`) are declared before the workload
// (`.addDocker()`) so the workload's `env` callback can bind to the Secret keys
// the operators generate. Anything the builder doesn't model goes in
// `.configure()`, which hands back the raw cdk8s scope and the resource handles.

import { ApiObject, App, Chart } from "cdk8s";
import { Construct } from "constructs";
import * as kube from "../imports/k8s";
import * as cnpg from "../imports/postgresql.cnpg.io.ts";
import * as barman from "../imports/barmancloud.cnpg.io.ts";
import * as garage from "../imports/garage.rajsingh.info.ts";
import * as environment from "./environment.ts";
import { DevStorageClass, ProdStorageClass, storageClass } from "./storageClass.ts";

// --- env values -----------------------------------------------------------

/**
 * A value in a workload's `env` map. The map key is always the name of the
 * primary environment variable; a value may emit additional variables (e.g. a
 * connection string's components) through `apply`.
 *
 * `app` is only needed by values that register resources, such as manual
 * secrets.
 */
export abstract class EnvRef {
    abstract apply(name: string, app: KirDevApp): kube.EnvVar[];
}

/**
 * A reference to one key of a Kubernetes Secret. Secrets are never passed
 * around as values: cdk8s manifests are committed to Git, and the values are
 * either generated by an operator (CNPG, garage-operator) or filled in by hand.
 *
 * `envName` is the variable an `interpolate` template emits for this ref; when
 * the ref is used directly as an `env` value, the map key is used instead.
 */
export class SecretKeyRef extends EnvRef {
    constructor(
        readonly secret: string,
        readonly key: string,
        readonly envName: string,
    ) {
        super();
    }
    apply(name: string): kube.EnvVar[] {
        return [{ name, valueFrom: { secretKeyRef: { name: this.secret, key: this.key } } }];
    }
}

/** A string assembled from `SecretKeyRef`s by the `interpolate` tag. */
export class Interpolated extends EnvRef {
    constructor(
        readonly value: string,
        readonly refs: readonly SecretKeyRef[],
    ) {
        super();
    }
    apply(name: string, app: KirDevApp): kube.EnvVar[] {
        const components = [...new Set(this.refs)].flatMap((ref) => ref.apply(ref.envName));
        return [...components, { name, value: this.value }];
    }
}

/**
 * A key of the app's manually-populated `${app.name}-secrets` Secret. The env
 * var name defaults to the map key; pass an explicit key to reuse one value
 * under several names.
 */
export class ManualSecret extends EnvRef {
    constructor(readonly key?: string) {
        super();
    }
    apply(name: string, app: KirDevApp): kube.EnvVar[] {
        const key = this.key ?? name;
        return [{ name, valueFrom: { secretKeyRef: { name: app.appSecrets(), key } } }];
    }
}

export function manualSecret(key?: string): ManualSecret {
    return new ManualSecret(key);
}

/**
 * Tagged template for connection strings: the refs become `$(ENV)` placeholders
 * (resolved by Kubernetes against sibling env vars) and are emitted as their
 * own variables.
 *
 *     ConnectionStrings__Postgres: interpolate`Host=${db.host}; ...`
 */
export function interpolate(strings: TemplateStringsArray, ...refs: SecretKeyRef[]): Interpolated {
    let value = strings[0];
    refs.forEach((ref, i) => {
        value += `$(${ref.envName})` + strings[i + 1];
    });
    return new Interpolated(value, refs);
}

export type EnvValue = string | EnvRef;
export type EnvSpec = Record<string, EnvValue>;

